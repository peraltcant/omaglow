Kind kindOf(const Action &action) {
    for (const Choice &c : specialChoices())
        if (c.action == action)
            return c.kind;
    return KeyPress;
}

QString labelOf(const Action &action) {
    for (const Choice &c : specialChoices())
        if (c.action == action)
            return c.label;
    if (const Key *k = find(action.code))
        return k->label;
    return QString::asprintf("0x%02X", action.code);
}

